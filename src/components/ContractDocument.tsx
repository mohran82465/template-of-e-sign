import React from 'react';
import { BilingualText, ContractData, ConfirmationMethod } from '../types';

interface ContractDocumentProps {
  contract: ContractData;
  isFilled: boolean;
  signDate: string;
  signatureImage: string | null;
  method: ConfirmationMethod | 'none';
  acceptedAt?: string;
  auditHash?: string;
  documentRef?: React.RefObject<HTMLDivElement | null>;
}

const TOTAL_PAGES = 2;

const formatAcceptedAt = (isoString: string) =>
  new Date(isoString).toLocaleString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  });

// English and Arabic captions share one run, separated by a middle dot
const Caption: React.FC<BilingualText> = ({ en, ar }) => (
  <span className="text-contract-muted">
    {en} · {ar}
  </span>
);

const SectionHeading: React.FC<{ number: string; title: BilingualText }> = ({ number, title }) => (
  <div className="flex items-center justify-between border-b-2 border-contract-green pb-1 mb-2 font-bold text-contract-green">
    <h2 className="text-[12px] tracking-wider uppercase">
      {number}&nbsp;&nbsp;{title.en}
    </h2>
    <h2 dir="rtl" className="text-[13px]">
      {number}&nbsp;&nbsp;{title.ar}
    </h2>
  </div>
);

const InfoRow: React.FC<{ label: BilingualText; value: string }> = ({ label, value }) => (
  <div className="flex items-center justify-between gap-3 border-b border-contract-line py-[3px]">
    <Caption {...label} />
    <span className="font-semibold text-right">{value}</span>
  </div>
);

const PartyHeading: React.FC<{ en: string; ar: string }> = ({ en, ar }) => (
  <div className="flex items-center justify-between pb-1 font-bold text-contract-subtle">
    <span className="text-[10.5px] tracking-wider uppercase">{en}</span>
    <span dir="rtl" className="text-[12px]">{ar}</span>
  </div>
);

const Page: React.FC<{ children: React.ReactNode }> = ({ children }) => (
  <section
    data-pdf-page
    className="contract-page paper-shadow w-full max-w-[794px] sm:min-h-[1123px] bg-white text-contract-ink text-[11.5px] leading-snug font-contract flex flex-col border-t-[6px] border-contract-green"
  >
    <div className="flex-1 flex flex-col px-5 sm:px-10 pt-6 pb-5">{children}</div>
  </section>
);

const PageFooter: React.FC<{ contract: ContractData; page: number; continuation?: BilingualText }> = ({
  contract,
  page,
  continuation,
}) => (
  <footer className="mt-auto pt-2">
    <div className="border-t border-contract-line pt-1.5 text-[10.5px] text-contract-muted">
      {continuation && (
        <p className="text-right text-contract-subtle">
          {continuation.en} · {continuation.ar}
        </p>
      )}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-x-3 pt-0.5">
        <span>
          Printed by {contract.printedBy} · {contract.printedAt} · Contract {contract.contractNumber}
        </span>
        <span>
          Page {page} of {TOTAL_PAGES} · Generated by Mudabbir
        </span>
      </div>
    </div>
  </footer>
);

export const ContractDocument: React.FC<ContractDocumentProps> = ({
  contract,
  isFilled,
  signDate,
  signatureImage,
  method,
  acceptedAt,
  auditHash,
  documentRef,
}) => {
  const { property, guest, stay, financials } = contract;

  const stayCards: { label: BilingualText; value: string }[] = [
    { label: { en: 'Unit', ar: 'الوحدة' }, value: stay.unit },
    { label: { en: 'Category', ar: 'الفئة' }, value: stay.category },
    { label: { en: 'Arrival', ar: 'الوصول' }, value: stay.arrival },
    { label: { en: 'Departure', ar: 'المغادرة' }, value: stay.departure },
    { label: { en: 'Nights', ar: 'الليالي' }, value: stay.nights },
    { label: { en: 'Occupancy', ar: 'الإشغال' }, value: stay.occupancy },
    { label: { en: 'Rate Plan', ar: 'خطة السعر' }, value: stay.ratePlan },
    { label: { en: 'Meal Plan', ar: 'خطة الوجبات' }, value: stay.mealPlan },
  ];

  // Acceptance values come from the saved version once the contract is executed
  const acceptanceCells: { label: BilingualText; value: string }[] = [
    {
      label: { en: 'Accepted via', ar: 'طريقة القبول' },
      value: !isFilled ? contract.acceptance.via : method === 'signed' ? 'Signature' : 'Confirmation',
    },
    {
      label: { en: 'Accepted at', ar: 'وقت القبول' },
      value: isFilled && acceptedAt ? formatAcceptedAt(acceptedAt) : contract.acceptance.at,
    },
    { label: { en: 'Witnessed by', ar: 'بحضور' }, value: contract.acceptance.witnessedBy },
    {
      label: { en: 'Acceptance ID', ar: 'رقم القبول' },
      value: isFilled && auditHash ? `ACC-${auditHash.slice(2, 10).toUpperCase()}` : contract.acceptance.id,
    },
  ];

  return (
    <div
      ref={documentRef}
      id="printable-contract-document"
      className="contract-sheets w-full flex flex-col items-center gap-6 py-2 sm:py-4"
    >
      {/* PAGE 1 — Parties, stay, financial terms, policies */}
      <Page>
        {/* Letterhead */}
        <header className="flex flex-col sm:flex-row sm:items-start justify-between gap-3 mb-3">
          <div className="flex items-start gap-3">
            <div className="w-[58px] h-[58px] shrink-0 rounded-md border border-dashed border-contract-faint flex items-center justify-center text-[10px] text-contract-muted">
              Logo
            </div>
            <div>
              <p className="text-[15px] font-bold leading-tight">{property.name}</p>
              <div className="mt-0.5 text-[11px] text-contract-subtle space-y-px">
                <p>{property.legalName}</p>
                <p>VAT No. {property.vatNumber} · CR No. {property.crNumber}</p>
                <p>{property.shortAddress} · {property.phone}</p>
              </div>
            </div>
          </div>
          <div className="sm:text-right shrink-0">
            <h1 className="text-[22px] font-bold leading-tight text-contract-green">{contract.title.en}</h1>
            <p className="text-[18px] font-bold leading-tight text-contract-green">{contract.title.ar}</p>
            <p className="mt-1 text-[11px] text-contract-subtle">Arabic text prevails · النص العربي هو المعتمد</p>
          </div>
        </header>

        {/* Reference strip */}
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 rounded-md bg-contract-panel px-3.5 py-2 mb-3.5">
          {[
            { label: { en: 'Contract No.', ar: 'رقم العقد' }, value: contract.contractNumber },
            { label: { en: 'Reservation No.', ar: 'رقم الحجز' }, value: contract.reservationNumber },
            { label: { en: 'Contract Date', ar: 'تاريخ العقد' }, value: contract.date },
            { label: { en: 'T&C Version', ar: 'إصدار الشروط' }, value: contract.termsVersion },
          ].map((cell) => (
            <div key={cell.label.en}>
              <Caption {...cell.label} />
              <p className="font-bold text-[11.5px]">{cell.value}</p>
            </div>
          ))}
        </div>

        {/* 1. Parties */}
        <SectionHeading number="1" title={{ en: 'Parties', ar: 'أطراف العقد' }} />
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-x-6 gap-y-3 mb-3.5">
          <div>
            <PartyHeading en="First Party — Property" ar="الطرف الأول — المنشأة" />
            <InfoRow label={{ en: 'Legal Name', ar: 'الاسم النظامي' }} value={property.legalName} />
            <InfoRow label={{ en: 'CR No.', ar: 'السجل التجاري' }} value={property.crNumber} />
            <InfoRow label={{ en: 'Tourism Licence', ar: 'الترخيص السياحي' }} value={property.tourismLicence} />
            <InfoRow label={{ en: 'Represented by', ar: 'ويمثلها' }} value={property.representedBy} />
          </div>
          <div>
            <PartyHeading en="Second Party — Guest" ar="الطرف الثاني — الضيف" />
            <InfoRow label={{ en: 'Name', ar: 'الاسم' }} value={guest.name} />
            <InfoRow label={{ en: 'ID', ar: 'الهوية' }} value={guest.idDisplay} />
            <InfoRow label={{ en: 'Nationality', ar: 'الجنسية' }} value={guest.nationality} />
            <InfoRow label={{ en: 'Mobile', ar: 'الجوال' }} value={guest.mobile} />
          </div>
        </div>

        {/* 2. Accommodation & stay */}
        <SectionHeading number="2" title={{ en: 'Accommodation & Stay', ar: 'الوحدة والإقامة' }} />
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 mb-3.5">
          {stayCards.map((card) => (
            <div key={card.label.en} className="rounded-md border border-contract-line px-2.5 py-1.5">
              <Caption {...card.label} />
              <p className="font-bold">{card.value}</p>
            </div>
          ))}
        </div>

        {/* 3. Financial terms */}
        <SectionHeading number="3" title={{ en: 'Financial Terms', ar: 'الشروط المالية' }} />
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-x-6 gap-y-3 mb-3.5">
          <table className="w-full border-collapse">
            <thead>
              <tr className="border-b border-contract-faint text-contract-subtle">
                <th className="py-1 text-left font-semibold">Item · البند</th>
                <th className="py-1 text-right font-semibold">Rate</th>
                <th className="py-1 text-right font-semibold">Amount</th>
              </tr>
            </thead>
            <tbody>
              {financials.lineItems.map((item) => (
                <tr key={item.label.en} className="border-b border-contract-line last:border-contract-ink">
                  <td className="py-1">
                    <p>{item.label.en}</p>
                    <p className="text-contract-muted">{item.label.ar}</p>
                  </td>
                  <td className={`py-1 text-right align-top ${item.isPlaceholder ? 'text-contract-muted' : ''}`}>
                    {item.rate}
                  </td>
                  <td className={`py-1 text-right align-top ${item.isPlaceholder ? 'text-contract-muted' : 'font-bold'}`}>
                    {item.amount}
                  </td>
                </tr>
              ))}
            </tbody>
            <tfoot>
              <tr className="text-[12px] font-bold">
                <td colSpan={2} className="pt-1.5">Total Contract Value · إجمالي قيمة العقد</td>
                <td className="pt-1.5 text-right">{financials.total}</td>
              </tr>
            </tfoot>
          </table>

          <div className="flex flex-col justify-between gap-3">
            <div>
              <InfoRow
                label={{ en: 'Advance Deposit Received', ar: 'الدفعة المقدمة المستلمة' }}
                value={financials.advanceDeposit}
              />
              <InfoRow
                label={{ en: 'Balance Payable at Check-out', ar: 'المتبقي عند المغادرة' }}
                value={financials.balance}
              />
              <InfoRow
                label={{ en: 'Security Deposit Required', ar: 'مبلغ التأمين المطلوب' }}
                value={financials.securityDeposit}
              />
              <InfoRow label={{ en: 'Accepted Payment', ar: 'طرق الدفع' }} value={financials.acceptedPayment} />
            </div>
            <p className="text-[10.5px] text-contract-muted">
              All amounts in SAR. Rates are per night. جميع المبالغ بالريال السعودي، والأسعار لكل ليلة.
            </p>
          </div>
        </div>

        {/* 4. Policies */}
        <SectionHeading number="4" title={{ en: 'Policies Applied', ar: 'السياسات المطبقة' }} />
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-2.5">
          {contract.policies.map((policy) => (
            <article key={policy.title.en} className="rounded-md border border-contract-line px-3 py-2">
              <div className="flex items-center justify-between gap-2 font-bold">
                <span>{policy.title.en}</span>
                <span dir="rtl">{policy.title.ar}</span>
              </div>
              <p className="mt-1 text-[10.5px] text-contract-muted">{policy.reference}</p>
              <p className="mt-1">{policy.body.en}</p>
              <p dir="rtl" className="mt-1">{policy.body.ar}</p>
            </article>
          ))}
        </div>
        <p className="mt-2 text-[10.5px] text-contract-muted">
          Policy wording is fixed at the version in force on the contract date. تُعتمد صياغة السياسات حسب الإصدار الساري في تاريخ العقد.
        </p>

        <PageFooter contract={contract} page={1} continuation={{ en: 'Continued on page 2', ar: 'يتبع في الصفحة 2' }} />
      </Page>

      {/* PAGE 2 — Terms of stay, signatures, acceptance record */}
      <Page>
        {/* Running header */}
        <header className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-contract-line pb-2.5 mb-3">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-md border border-dashed border-contract-faint" />
            <span className="text-[12.5px] font-bold">{property.name}</span>
          </div>
          <div className="flex flex-wrap items-baseline gap-x-2.5">
            <span className="text-[13px] font-bold text-contract-green">
              {contract.title.en} · {contract.title.ar}
            </span>
            <span className="text-[11px] text-contract-subtle">
              {contract.contractNumber} · {contract.reservationNumber}
            </span>
          </div>
        </header>

        {/* 5. Terms of stay */}
        <SectionHeading number="5" title={{ en: 'Terms of Stay', ar: 'شروط الإقامة' }} />
        <div className="mb-3">
          {contract.clauses.map((clause) => (
            <article
              key={clause.number}
              className="grid grid-cols-1 sm:grid-cols-2 gap-x-6 gap-y-1 border-b border-contract-line py-1.5"
            >
              <div>
                <h3 className="font-bold">
                  {clause.number}&nbsp;&nbsp;{clause.title.en}
                </h3>
                <p className="mt-0.5 text-contract-subtle">{clause.body.en}</p>
              </div>
              <div dir="rtl">
                <h3 className="font-bold">
                  {clause.number}&nbsp;&nbsp;{clause.title.ar}
                </h3>
                <p className="mt-0.5 text-contract-subtle">{clause.body.ar}</p>
              </div>
            </article>
          ))}
        </div>

        {/* 6. Signatures */}
        <SectionHeading number="6" title={{ en: 'Signatures', ar: 'التواقيع' }} />
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-x-6 gap-y-3 mb-2.5">
          {/* First Party */}
          <div className="rounded-md border border-contract-line px-3 py-2">
            <PartyHeading en="First Party" ar="الطرف الأول" />
            <SignatureRow label={{ en: 'Name', ar: 'الاسم' }} value={property.representativeName} />
            <SignatureRow label={{ en: 'Title', ar: 'الصفة' }} value={property.representativeTitle} />
            <SignatureRow label={{ en: 'Date', ar: 'التاريخ' }} value={contract.date} />
            <SignatureLine />
          </div>

          {/* Second Party */}
          <div className="rounded-md border border-contract-line px-3 py-2">
            <PartyHeading en="Second Party" ar="الطرف الثاني" />
            <SignatureRow label={{ en: 'Name', ar: 'الاسم' }} value={guest.name} />
            <SignatureRow label={{ en: 'ID', ar: 'الهوية' }} value={guest.idDisplay} />
            <SignatureRow
              label={{ en: 'Date', ar: 'التاريخ' }}
              value={isFilled && signDate ? signDate : 'Pending'}
            />
            <SignatureLine>
              {isFilled &&
                (method === 'signed' && signatureImage ? (
                  <img
                    src={signatureImage}
                    alt="Guest signature"
                    className="max-h-full max-w-[220px] object-contain"
                  />
                ) : (
                  <span className="font-semibold text-contract-green">Confirmed electronically</span>
                ))}
            </SignatureLine>
          </div>
        </div>

        {/* Acceptance record */}
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 rounded-md bg-contract-panel px-3.5 py-2">
          {acceptanceCells.map((cell) => (
            <div key={cell.label.en}>
              <Caption {...cell.label} />
              <p className="font-bold text-[11.5px]">{cell.value}</p>
            </div>
          ))}
        </div>

        <PageFooter contract={contract} page={2} />
      </Page>
    </div>
  );
};

const SignatureRow: React.FC<{ label: BilingualText; value: string }> = ({ label, value }) => (
  <div className="flex items-center justify-between gap-3 py-px">
    <Caption {...label} />
    <span className="font-semibold text-right">{value}</span>
  </div>
);

const SignatureLine: React.FC<{ children?: React.ReactNode }> = ({ children }) => (
  <div className="mt-1">
    <div className="h-14 flex items-end justify-center border-b border-contract-subtle pb-1">{children}</div>
    <div className="flex items-center justify-between pt-1 text-contract-muted">
      <span>Signature</span>
      <span dir="rtl">التوقيع</span>
    </div>
  </div>
);
